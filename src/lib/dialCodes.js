/** Every distinct dial code, longest first, for prefix matching. */
const DIAL_CODES_BY_LENGTH = Array.from(new Set(COUNTRIES.map((c) => c[0])))
  .sort((a, b) => b.length - a.length);

/** ISO -> dial, for defaulting the picker off a detected country. */
